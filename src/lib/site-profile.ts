/**
 * Sprint 12 — SITE_PROFILE par domaine.
 *
 * Chaque domaine a son propre profile : palette enrichie, outils activés,
 * catégories thématiques, persona, hero rich, mots-clés cibles SEO,
 * imagery hints (pour fetch Wikipedia Commons).
 *
 * Importé par site-config.ts → injecté dans toutes les pages via SITE_CONFIG.profile.
 */

import type { ArchetypeId } from './page-archetypes';

export interface SiteProfile {
  domain: string;
  // Archétype STRUCTUREL (6) — pilote la home sur-mesure + la nav (HOME_SECTIONS,
  // ARCHETYPES[].nav). Optionnel : si absent, index.astro/Header dérivent via
  // inferArchetype(profile) (geo→local_place, matchups→comparator, défaut éditorial).
  archetype?: ArchetypeId;
  // Variant de layout (anti-footprint Google) : chaque site a un layout différent
  // luxe = Lelo style (cream + serif italic + photos full-bleed) → adulte
  // magazine = Vogue/NYT style (typo plus petite, plus dense) → villages
  // tech = Wirecutter style (clean blanc, tableaux, less photo) → tech/ecom
  // lifestyle = Manufactum style (couleur terre, photos d'action) → bricolage
  layoutVariant: 'luxe' | 'magazine' | 'tech' | 'lifestyle';
  // Identité éditoriale
  positioning: string;      // 1 phrase positionnement (apparait dans hero)
  mission: string;          // mission longue (apparait dans /a-propos)
  uniqueValue: string;      // ce qui différencie ce site (sur homepage)
  targetAudience: string;   // qui on adresse
  // Persona auteur principal
  author: { name: string; role: string; credentials: string; bio: string };
  // Catégories thématiques (utilisées pour /categorie/[cat]/ + classification articles)
  categories: Array<{
    slug: string;
    name: string;
    description: string;
    keywords: string[];     // mots du titre qui matchent cette catégorie (classifier)
    emoji?: string;
  }>;
  // Outils activés sur ce site (subset des fichiers /pages/outils/)
  tools: Array<{
    slug: string;        // doit matcher un fichier dans /pages/outils/<slug>.astro
    label: string;
    emoji: string;
    description: string;
    seoKeyword: string;  // requête principale ciblée
    href?: string;       // override si page n'est pas sous /outils/ (ex: /glossaire/)
  }>;
  // Hero homepage
  hero: {
    title: string;
    subtitle: string;
    intro: string;       // paragraphe complet
    primaryCta: { label: string; href: string };
    secondaryCta: { label: string; href: string };
    badges: string[];    // trust signals
    imageHint: string;   // mot-clé pour Wikipedia Commons (background hero)
  };
  // Mots-clés SEO cibles globaux (top 10-20)
  targetKeywords: string[];
  // Concurrents/leaders à étudier (pour benchmarking)
  competitors: string[];
  // Images Wikipedia Commons par sujet à pré-fetcher
  wikiImageSubjects: string[];
  // Trust signals affichés dans homepage / footer
  trustBadges: Array<{ emoji: string; label: string; tooltip: string }>;
  // Verification Search Console (Google) : meta tag injectée dans <head> si défini
  gscVerification?: string;
  // Verification Bing Webmaster Tools : meta tag injectée si défini
  bingVerification?: string;
  // Coordonnées géo pour ranking local (commune, département)
  geo?: {
    region: string;     // ISO ex 'FR-24' (Dordogne)
    placename: string;  // ex 'Gardonne'
    lat: number;        // ex 44.852
    lng: number;        // ex 0.290
    wikidataId?: string;     // ex 'Q586049' (Gardonne sur Wikidata)
    parentEntities?: Array<{ name: string; wikidataId: string; url?: string }>;
    // Bergerac, Dordogne, Périgord pourpre, etc.
  };
  // sameAs pour l'auteur principal (LinkedIn, Twitter, autres profils publics)
  authorSameAs?: string[];
  // Liens externes "autorité" affichés dans le footer/about (boost trust)
  authorityLinks?: Array<{ label: string; url: string; nofollow?: boolean }>;
  // Presets calculator override (sinon utilise archetype defaults)
  calculatorPresets?: Array<{
    id: string;
    label: string;
    emoji: string;
    vars: Array<{ key: string; label: string; unit: string; default: number }>;
    formula: string;       // expression JS
    result: string;        // unité résultat
    explain: string;       // contenu éducatif (apparait sous le calc)
  }>;
  // Matchups X-vs-Y programmatiques (pour /comparatif/<a>-vs-<b>/ pages)
  matchups?: Array<{
    slug: string;          // ex: "womanizer-vs-satisfyer"
    productA: { name: string; positioning: string; strengths: string[]; weaknesses: string[]; price: string };
    productB: { name: string; positioning: string; strengths: string[]; weaknesses: string[]; price: string };
    criteria: Array<{ label: string; a: string; b: string; winner?: 'a' | 'b' | 'tie' }>;
    conclusion: string;
    bestFor: { a: string; b: string };
  }>;
}

